import { Prisma } from "@prisma/client";
import { prisma } from "../config/prisma";
import { AppError } from "../middleware/error.middleware";
import { HTTP_STATUS } from "../shared/constants";

export interface P0RecoveryInput {
  userId:               string;
  withdrawalRequestId:  string;
  overpaidAmount:       number;
  reason:               string;
}

export interface P0RecoveryResult {
  userId:                  string;
  username:                string;
  withdrawalRequestId:     string;
  withdrawalAmountReturned: string;
  recoveredAmount:          string;
  finalWithdrawalWallet:    string;
  recoveryTxId:             string;
  reason:                  string;
}

/**
 * P0 Power BV Recovery
 *
 * Atomically:
 *  1. Validates the withdrawal is in MANUAL_REVIEW and belongs to the user.
 *  2. Rejects the withdrawal request (funds were never sent — tx reverted on-chain).
 *  3. Credits the withdrawal amount back to withdrawalWallet.
 *  4. Debits the overpaid amount as a POWER_BV_RECOVERY walletTransaction.
 *  5. Records a POWER_BV_RECOVERY entry in the financial_ledger.
 *  6. Creates an AdminLog entry.
 *
 * Net wallet effect: zero (credit + immediate debit of same amount).
 * Audit trail: two walletTransaction records + one financial_ledger DEBIT.
 */
export async function executeP0PowerBvRecovery(
  adminId: string,
  input:   P0RecoveryInput,
): Promise<P0RecoveryResult> {
  const { userId, withdrawalRequestId, overpaidAmount, reason } = input;

  const overpaidDecimal = new Prisma.Decimal(overpaidAmount);

  const wr = await prisma.withdrawalRequest.findUnique({
    where:  { id: withdrawalRequestId },
    select: { id: true, userId: true, amount: true, status: true },
  });
  if (!wr) {
    throw new AppError("Withdrawal request not found", HTTP_STATUS.NOT_FOUND, "NOT_FOUND");
  }
  if (wr.userId !== userId) {
    throw new AppError("Withdrawal request does not belong to this user", HTTP_STATUS.BAD_REQUEST, "USER_MISMATCH");
  }
  if (wr.status !== "MANUAL_REVIEW") {
    throw new AppError(
      `Withdrawal is ${wr.status} — only MANUAL_REVIEW withdrawals can be processed via P0 recovery`,
      HTTP_STATUS.BAD_REQUEST,
      "WRONG_STATUS",
    );
  }

  const user = await prisma.user.findUnique({
    where:  { id: userId },
    select: { id: true, username: true },
  });
  if (!user) {
    throw new AppError("User not found", HTTP_STATUS.NOT_FOUND, "USER_NOT_FOUND");
  }

  const wallet = await prisma.wallet.findUnique({
    where:  { userId },
    select: { id: true, withdrawalWallet: true },
  });
  if (!wallet) {
    throw new AppError("Wallet not found", HTTP_STATUS.NOT_FOUND, "WALLET_NOT_FOUND");
  }

  const balanceBeforeReturn = wallet.withdrawalWallet;
  const balanceAfterReturn  = balanceBeforeReturn.add(wr.amount);
  const balanceAfterDebit   = balanceAfterReturn.sub(overpaidDecimal);

  let recoveryTxId = "";

  await prisma.$transaction(async (tx) => {
    await tx.withdrawalRequest.update({
      where: { id: withdrawalRequestId },
      data:  {
        status:      "REJECTED",
        adminNotes:  `P0 Power BV Recovery — ${reason}. Withdrawal rejected: funds generated by accidental Power BV assignment; on-chain tx had already reverted (MANUAL_REVIEW). No crypto was sent to user.`,
        processedAt: new Date(),
      },
    });

    await tx.wallet.update({
      where: { id: wallet.id },
      data:  { withdrawalWallet: { increment: wr.amount } },
    });

    await tx.walletTransaction.create({
      data: {
        walletId:    wallet.id,
        userId,
        type:        "WITHDRAWAL",
        status:      "SUCCESS",
        amount:      wr.amount,
        description: `P0 Recovery: withdrawal request ${withdrawalRequestId} rejected — on-chain tx reverted, funds returned`,
        metadata:    { p0Recovery: true, reason, withdrawalRequestId, performedBy: adminId },
      },
    });

    const recoveryTx = await tx.walletTransaction.create({
      data: {
        walletId:    wallet.id,
        userId,
        type:        "POWER_BV_RECOVERY",
        status:      "SUCCESS",
        amount:      overpaidDecimal,
        description: `P0 Recovery: debit of excess Binary Matching income caused by accidental Power BV assignment. ${reason}`,
        metadata:    {
          p0Recovery:                    true,
          reason,
          withdrawalRequestId,
          performedBy:                   adminId,
          originalMatchingBonusAmount:   overpaidAmount,
        },
      },
    });

    recoveryTxId = recoveryTx.id;

    await tx.wallet.update({
      where: { id: wallet.id },
      data:  { withdrawalWallet: { decrement: overpaidDecimal } },
    });

    await tx.financialLedger.create({
      data: {
        referenceId:     recoveryTx.id,
        referenceType:   "p0_power_bv_recovery",
        memberId:        userId,
        username:        user.username,
        transactionType: "POWER_BV_RECOVERY",
        amount:          overpaidDecimal,
        debitCredit:     "DEBIT",
        walletType:      "WITHDRAWAL_WALLET",
        openingBalance:  balanceAfterReturn,
        closingBalance:  balanceAfterDebit,
        metadata:        { reason, withdrawalRequestId, performedBy: adminId },
      },
    });

    await tx.adminLog.create({
      data: {
        adminId,
        action:       "WALLET_ADJUSTMENT",
        targetUserId: userId,
        details: {
          operation:            "p0_power_bv_recovery",
          overpaidAmount:       overpaidDecimal.toString(),
          withdrawalRequestId,
          withdrawalAmount:     wr.amount.toString(),
          balanceBeforeReturn:  balanceBeforeReturn.toString(),
          balanceAfterReturn:   balanceAfterReturn.toString(),
          balanceAfterDebit:    balanceAfterDebit.toString(),
          reason,
          username:             user.username,
        },
      },
    });
  });

  return {
    userId,
    username:                 user.username,
    withdrawalRequestId,
    withdrawalAmountReturned: wr.amount.toString(),
    recoveredAmount:          overpaidDecimal.toString(),
    finalWithdrawalWallet:    balanceAfterDebit.toString(),
    recoveryTxId,
    reason,
  };
}
